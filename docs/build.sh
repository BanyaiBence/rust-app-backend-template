#!/usr/bin/env bash
# Builds the architecture documentation:
#   1. renders docs/architecture/*.puml to docs/rendered/*.svg (committed, so the diagrams can
#      be viewed without a build)
#   2. converts the SVGs to vector PDFs in docs/build/figures/
#   3. writes docs/build/diagrams.tex: one section per diagram, in .puml file name order
#   4. compiles docs/architecture.tex into docs/build/architecture.pdf
#
# Each section is titled by the diagram's `title` line (the file name if there is none). Prose
# for a section goes in docs/architecture/<name>.tex next to <name>.puml; it is optional.
#
# Usage: docs/build.sh [--svg-only]   (or `make diagrams` / `make architecture`)
#
# Needs: plantuml (or Docker), rsvg-convert (or inkscape), and latexmk with pdflatex.
set -euo pipefail
shopt -s nullglob

cd "$(dirname "$0")"

svg_only=false
case "${1:-}" in
  "") ;;
  --svg-only) svg_only=true ;;
  *) echo "usage: $0 [--svg-only]" >&2; exit 2 ;;
esac

die() { echo "error: $*" >&2; exit 1; }

sources=(architecture/*.puml)
((${#sources[@]})) || die "no diagrams found in $PWD/architecture/*.puml"

# The SVG name PlantUML picks: the name after @startuml if given, else the file's base name.
svg_name() {
  local name
  name=$(sed -n 's/^@startuml[[:space:]]\{1,\}\([^[:space:]]\{1,\}\).*/\1/p' "$1" | head -n 1)
  echo "${name:-$(basename "${1%.puml}")}"
}

# Escapes the LaTeX special characters that can appear in a diagram title.
latex_escape() {
  sed -e 's/[&%$#_{}]/\\&/g' -e 's/~/\\textasciitilde{}/g' -e 's/\^/\\textasciicircum{}/g'
}

# 1. PlantUML -> SVG (cleared first so renamed or deleted diagrams leave nothing behind)
rm -f rendered/*.svg
if command -v plantuml >/dev/null; then
  plantuml -tsvg -o ../rendered "${sources[@]}"
elif command -v docker >/dev/null; then
  docker run --rm -u "$(id -u):$(id -g)" -v "$PWD:/docs" -w /docs/architecture \
    plantuml/plantuml -tsvg -o ../rendered ./*.puml
else
  die "plantuml or docker is required"
fi
echo "Rendered SVGs to $PWD/rendered/"

$svg_only && exit 0

# 2. SVG -> PDF, so LaTeX can embed the diagrams as vector graphics.
rm -rf build/figures
mkdir -p build/figures
for svg in rendered/*.svg; do
  pdf="build/figures/$(basename "${svg%.svg}").pdf"
  if command -v rsvg-convert >/dev/null; then
    rsvg-convert -f pdf -o "$pdf" "$svg"
  elif command -v inkscape >/dev/null; then
    inkscape "$svg" --export-type=pdf --export-filename="$pdf" >/dev/null 2>&1
  else
    die "rsvg-convert (librsvg) or inkscape is required to embed diagrams in the PDF"
  fi
done

# 3. The diagram sections, included by architecture.tex.
{
  echo "% Generated by build.sh from architecture/*.puml; do not edit."
  for src in "${sources[@]}"; do
    name=$(svg_name "$src")
    [[ -f "build/figures/$name.pdf" ]] || die "$src did not render to rendered/$name.svg"
    title=$(sed -n 's/^title[[:space:]]\{1,\}//p' "$src" | head -n 1)
    title=$(printf '%s' "${title:-$name}" | latex_escape)
    prose="${src%.puml}.tex"
    [[ -f "$prose" ]] || prose=""
    printf '\\architecturediagram{%s}{%s}{%s}\n' "$name" "$title" "$prose"
  done
} > build/diagrams.tex

# 4. LaTeX -> PDF
command -v latexmk >/dev/null || die "latexmk and pdflatex (TeX Live) are required to build the PDF"

revision=$(git describe --always --dirty 2>/dev/null || echo unknown)
printf '\\newcommand{\\docversion}{%s}\n' "$revision" > build/version.tex

latexmk -pdf -outdir=build -interaction=nonstopmode -halt-on-error -quiet architecture.tex \
  || die "LaTeX build failed; see $PWD/build/architecture.log"

echo "Built $PWD/build/architecture.pdf"
